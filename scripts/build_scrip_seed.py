"""Generate supabase/migrations/0002_seed_scrips.sql from data/indian_stock_tickers.csv.

Run from the repo root:  python scripts/build_scrip_seed.py
"""

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "data" / "indian_stock_tickers.csv"
SQL_PATH = ROOT / "supabase" / "migrations" / "0002_seed_scrips.sql"


def sql_text(value: str | None) -> str:
    if not value:
        return "null"
    return "'" + value.replace("'", "''") + "'"


def build_rows() -> list[tuple[str, str | None, str, str, str | None]]:
    """Return (bse_code, nse_symbol, yahoo_symbol, name, fyers_symbol), first row wins per BSE code."""
    seen: set[str] = set()
    rows = []
    with CSV_PATH.open(encoding="utf-8-sig", newline="") as f:
        for rec in csv.DictReader(f):
            code = rec["BSE Code"].strip()
            if not code or code in seen:
                continue
            seen.add(code)
            yahoo = rec["Yahoo Symbol"].strip()
            symbol, _, suffix = yahoo.rpartition(".")
            nse = symbol if suffix == "NS" else None
            # BSE-only scrips get their Fyers symbol later from the Fyers symbol master.
            fyers = f"NSE:{nse}-EQ" if nse else None
            rows.append((code, nse, yahoo, rec["Company Name"].strip(), fyers))
    return rows


def main() -> None:
    rows = build_rows()
    values = ",\n".join(
        f"  ({sql_text(c)}, {sql_text(n)}, {sql_text(y)}, {sql_text(name)}, {sql_text(f)})"
        for c, n, y, name, f in rows
    )
    SQL_PATH.write_text(
        "-- Generated by scripts/build_scrip_seed.py from data/indian_stock_tickers.csv. Do not edit.\n\n"
        "insert into scrips (bse_code, nse_symbol, yahoo_symbol, name, fyers_symbol) values\n"
        f"{values}\n"
        "on conflict (bse_code) do nothing;\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} scrips to {SQL_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
